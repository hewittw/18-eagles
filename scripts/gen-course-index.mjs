// Regenerate src/data/courses/index.ts from the JSON files (only files that pass check-courses.mjs).
// Usage: node scripts/gen-course-index.mjs
import fs from "fs";
import path from "path";
import { execFileSync } from "child_process";
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const dir = path.join(root, "src/data/courses");
const slugs = fs.readdirSync(dir).filter((f) => f.endsWith(".json")).map((f) => f.replace(".json", "")).sort()
  .filter((s) => { try { execFileSync("node", [path.join(root, "scripts/check-courses.mjs"), s], { stdio: "ignore" }); return true; } catch { console.log("skipped (fails check):", s); return false; } });
const id = (s) => "c_" + s.replace(/[^a-z0-9]/g, "_");
const out = `// Generated by scripts/gen-course-index.mjs. Don't edit by hand.
import type { Course } from "@/lib/course-types";
${slugs.map((s) => `import ${id(s)} from "./${s}.json";`).join("\n")}

export const BUILT_IN: Course[] = [${slugs.map(id).join(", ")}] as Course[];
`;
fs.writeFileSync(path.join(dir, "index.ts"), out);
console.log(`index.ts: ${slugs.length} courses`);
